func TestApplyWritesNewFile(t *testing.T) {
	tmp := t.TempDir()
	w := NewWriter(tmp, false)
	plan := &Plan{
		Target: "test",
		Files: []FileOp{
			{Path: "out.md", Content: []byte("hello\n"), Marker: true},
		},
	}
	written, skipped, err := w.Apply(plan)
	if err != nil {
		t.Fatal(err)
	}
	if written != 1 || skipped != 0 {
		t.Errorf("written=%d skipped=%d", written, skipped)
	}
	got, _ := os.ReadFile(filepath.Join(tmp, "out.md"))
	if string(got) != "hello\n" {
		t.Errorf("content = %q", got)
	}
}

