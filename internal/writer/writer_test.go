func TestBackupSnapshot(t *testing.T) {
	tmp := t.TempDir()
	root := filepath.Join(tmp, "proj")
	mustMkdir(t, root)
	mustWrite(t, filepath.Join(root, "CLAUDE.md"), "old content")

	backupDir := filepath.Join(tmp, "backups")
	b := NewBackup(backupDir, 3)
	dir, err := b.Snapshot(root, []string{"CLAUDE.md", "missing.md"})
	if err != nil {
		t.Fatal(err)
	}
	if dir == "" {
		t.Fatal("expected backup dir")
	}
	got, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if string(got) != "old content" {
		t.Errorf("backup content = %q", got)
	}
}

