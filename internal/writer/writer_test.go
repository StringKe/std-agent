func TestBackupPrune(t *testing.T) {
	tmp := t.TempDir()
	b := NewBackup(tmp, 2)

	for _, ts := range []string{
		"2026-01-01T00-00-00Z",
		"2026-02-01T00-00-00Z",
		"2026-03-01T00-00-00Z",
		"2026-04-01T00-00-00Z",
	} {
		dir := filepath.Join(tmp, ts)
		mustMkdir(t, dir)
		mustWrite(t, filepath.Join(dir, "x"), "y")
	}
	if err := b.prune(); err != nil {
		t.Fatal(err)
	}
	entries, _ := os.ReadDir(tmp)
	if len(entries) != 2 {
		t.Errorf("after prune: %d entries, want 2", len(entries))
	}
}

func TestSnapshotMultipleFilesWithMissing(t *testing.T) {
	tmp := t.TempDir()
	proj := filepath.Join(tmp, "proj")
	mustMkdir(t, proj)
	mustMkdir(t, filepath.Join(proj, ".claude/rules"))
	mustWrite(t, filepath.Join(proj, "CLAUDE.md"), "claude-content")
	mustWrite(t, filepath.Join(proj, "AGENTS.md"), "agents-content")
	mustWrite(t, filepath.Join(proj, ".claude/rules/style.md"), "style-content")

	b := NewBackup(filepath.Join(tmp, "backups"), 5)
	dir, err := b.Snapshot(proj, []string{
		"CLAUDE.md",
		"AGENTS.md",
		".claude/rules/style.md",
		"missing-file.md", // 应被跳过
	})
	if err != nil {
		t.Fatal(err)
	}
	if dir == "" {
		t.Fatal("expected non-empty backup dir")
	}
	for _, name := range []string{"CLAUDE.md", "AGENTS.md", ".claude/rules/style.md"} {
		c, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Errorf("backup %s missing: %v", name, err)
			continue
		}
		if len(c) == 0 {
			t.Errorf("backup %s empty", name)
		}
	}
	// missing-file 不应在 backup
	if _, err := os.Stat(filepath.Join(dir, "missing-file.md")); err == nil {
		t.Error("missing-file should not be backed up")
	}
}

func TestApplyMixedWrittenAndSkipped(t *testing.T) {
	tmp := t.TempDir()
	w := NewWriter(tmp, false)
	mustWrite(t, filepath.Join(tmp, "existing.md"), "same")

	plan := &Plan{
		Files: []FileOp{
			{Path: "new1.md", Content: []byte("new content 1")},
			{Path: "existing.md", Content: []byte("same")}, // skip
			{Path: "subdir/new2.md", Content: []byte("new content 2")},
		},
	}
	written, skipped, err := w.Apply(plan)
	if err != nil {
		t.Fatal(err)
	}
	if written != 2 {
		t.Errorf("written = %d, want 2", written)
	}
	if skipped != 1 {
		t.Errorf("skipped = %d, want 1", skipped)
	}

	// 验证 subdir 自动创建
	if _, err := os.Stat(filepath.Join(tmp, "subdir/new2.md")); err != nil {
		t.Errorf("subdir/new2.md missing: %v", err)
	}
	// 验证 plan.Files[1].Skip 被设置
	if !plan.Files[1].Skip {
		t.Error("existing.md FileOp.Skip should be set")
	}
}

func TestApplySkipsWhenOnlyMarkerTimestampDiffers(t *testing.T) {
	tmp := t.TempDir()
	w := NewWriter(tmp, false)

	oldHeader := "<!-- Generated by stdagent v0.1.0 at 2026-01-01T00:00:00Z. Source: .stdai/standards/rules/style.md. Run `stdagent sync` to regenerate. Do not edit by hand. -->\n"
	newHeader := "<!-- Generated by stdagent v0.1.0 at 2026-05-10T08:32:11Z. Source: .stdai/standards/rules/style.md. Run `stdagent sync` to regenerate. Do not edit by hand. -->\n"
	body := "# Style\n\nbody content\n<!-- /Generated by stdagent -->\n"
	mustWrite(t, filepath.Join(tmp, "out.md"), oldHeader+body)

	statBefore, _ := os.Stat(filepath.Join(tmp, "out.md"))

	plan := &Plan{
		Files: []FileOp{
			{Path: "out.md", Content: []byte(newHeader + body), Marker: true},
		},
	}
	written, skipped, err := w.Apply(plan)
	if err != nil {
		t.Fatal(err)
	}
	if written != 0 || skipped != 1 {
		t.Errorf("written=%d skipped=%d, want 0/1", written, skipped)
	}
	if !plan.Files[0].Skip || plan.Files[0].Reason != "unchanged" {
		t.Errorf("op = %+v", plan.Files[0])
	}
	statAfter, _ := os.Stat(filepath.Join(tmp, "out.md"))
	if !statBefore.ModTime().Equal(statAfter.ModTime()) {
		t.Errorf("mtime should not change: before=%v after=%v", statBefore.ModTime(), statAfter.ModTime())
	}
	got, _ := os.ReadFile(filepath.Join(tmp, "out.md"))
	if string(got) != oldHeader+body {
		t.Errorf("file content should be untouched, got %q", got)
	}
}

