func TestFileExistsAndChecksum(t *testing.T) {
	tmp := t.TempDir()
	exists := filepath.Join(tmp, "a.txt")
	mustWrite(t, exists, "hello")
	if !FileExists(exists) {
		t.Error("FileExists should return true")
	}
	if FileExists(filepath.Join(tmp, "nope.txt")) {
		t.Error("FileExists should return false for missing")
	}

	hash := Checksum([]byte("hello"))
	if hash != "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824" {
		t.Errorf("Checksum hello = %s", hash)
	}
}

func mustWrite(t *testing.T, p, c string) {
	t.Helper()
	if err := os.WriteFile(p, []byte(c), 0o600); err != nil {
		t.Fatal(err)
	}
}

func mustMkdir(t *testing.T, p string) {
	t.Helper()
	if err := os.MkdirAll(p, 0o755); err != nil {
		t.Fatal(err)
	}
}
